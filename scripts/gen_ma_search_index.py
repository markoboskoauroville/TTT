#!/usr/bin/env python3
"""Generates MaSearchIndex.kt: the words of every settings screen whose texts are written in the
code (not in strings.xml), so the settings search finds them (Marko, 13.11.2026: searching "groq",
which is on many screens, found nothing). Rerun after changing a screen:
    python3 scripts/gen_ma_search_index.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "app/src/main/kotlin/dev/patrickgold/florisboard"
ROUTES = (SRC / "app/Routes.kt").read_text()
OUT = SRC / "app/settings/search/MaSearchIndex.kt"

objects = set(re.findall(r"^\s*(?:data\s+)?object\s+(\w+)", ROUTES, re.M))
pairs = re.findall(r"composableWithDeepLink\(Settings\.(\w+)::class\)\s*\{\s*([\w.]*?)(\w+Screen)\(\)", ROUTES)

files = {p: p.read_text(errors="ignore") for p in (SRC / "app").rglob("*.kt")}
LIT = re.compile(r'"((?:[^"\\\n]|\\.){3,240})"')

def screen_file(fn):
    for p, t in files.items():
        if re.search(r"fun\s+" + fn + r"\s*\(", t):
            return p, t
    return None, None

def clean(s):
    s = re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: chr(int(m.group(1), 16)), s)
    s = re.sub(r"\$\{[^}]*\}|\$\w+", " ", s).replace("\\n", " ").replace('\\"', '"').replace("\\'", "'")
    return re.sub(r"\s+", " ", s).strip()

def kt(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

# The transcription engines are named in EngineCatalog, not on the screens that list them.
ENGINES = (SRC / "dictate/engines/EngineLogic.kt").read_text()
engine_words = []
for name, note in re.findall(r'EngineSpec\("[^"]+",\s*"([^"]+)",[^\n]*?"[^"]*",\s*"([^"]*)"\)', ENGINES):
    engine_words.append(name + (" (" + note + ")" if note else ""))
engine_words += ["Groq", "Groq Turbo, whisper-large-v3-turbo", "Groq v3, whisper-large-v3", "Whisper", "transcription engine, provider, model"]
EXTRA = {r: engine_words for r in ("MaTranscription", "MaVoiceButtons", "MaEngines", "DictateKeys")}

entries = []
for route, _, fn in pairs:
    if route not in objects or route in ("Home", "Search"):
        continue
    p, t = screen_file(fn)
    if not t:
        continue
    # the screen's own title: the first `title = "..."` right after `fun XScreen() = FlorisScreen {`
    body = t[re.search(r"fun\s+" + fn + r"\s*\(", t).start():]
    m = re.match(r'[^{]*\{\s*(?://[^\n]*\n\s*)*title\s*=\s*"([^"$]+)"', body)
    title = clean(m.group(1)) if m else re.sub(r"(?<!^)([A-Z])", r" \1", fn.removesuffix("Screen").removeprefix("Ma")).strip()
    texts, seen = [], set()
    for lit in LIT.findall(t):
        c = clean(lit)
        if any(ord(ch) < 32 for ch in c):
            continue
        if len(c) < 3 or not re.search(r"[A-Za-z]{3}", c) or re.fullmatch(r"[\w.:/-]+", c) and " " not in c and not re.search(r"[A-Z]", c[:1]):
            continue  # ids, keys, paths
        if c.lower() in seen:
            continue
        seen.add(c.lower()); texts.append(c[:200])
    texts += [e for e in EXTRA.get(route, []) if e.lower() not in seen]
    entries.append((title, route, texts))

with OUT.open("w") as f:
    f.write("""/*
 * GENERATED by scripts/gen_ma_search_index.py, do not edit by hand.
 * Licensed under the Apache License, Version 2.0.
 */

package dev.patrickgold.florisboard.app.settings.search

import dev.patrickgold.florisboard.app.Routes

/** A settings screen whose words live in the code: its title, its route and every text it shows. */
class MaSearchScreen(val title: String, val route: Any, val texts: List<String>)

object MaSearchIndex {
    val screens: List<MaSearchScreen> by lazy {
        listOf(
""")
    for title, route, texts in entries:
        f.write(f"            MaSearchScreen({kt(title)}, Routes.Settings.{route}, listOf(\n")
        for x in texts:
            f.write(f"                {kt(x)},\n")
        f.write("            )),\n")
    f.write("""        )
    }

    /** The screens whose title or texts contain [q], each with the first text that matched (for the summary). */
    fun search(q: String): List<Pair<MaSearchScreen, String?>> {
        if (q.isBlank()) return emptyList()
        val words = q.trim().split(Regex("\\\\s+"))
        return screens.mapNotNull { s ->
            val all = listOf(s.title) + s.texts
            if (words.all { w -> all.any { it.contains(w, ignoreCase = true) } }) {
                s to s.texts.firstOrNull { it.contains(words[0], ignoreCase = true) }
            } else null
        }.sortedByDescending { (s, _) -> s.title.contains(q.trim(), ignoreCase = true) }
    }
}
""")
print(f"{len(entries)} screens, {sum(len(e[2]) for e in entries)} texts -> {OUT}")
