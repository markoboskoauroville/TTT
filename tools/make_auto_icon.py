#!/usr/bin/env python3
"""MaAutoIcon.kt: the AUTO icon, the new icon standard (Marko, 9.11.2026): a WHITE rounded square with the
word CUT OUT (transparent letters), like Material FontDownload, which the 'A' of Auto prediction is. Same
square as FontDownload: 2..22 of the 24 box, corner radius 2. Text from Arial Bold, scaled to 16.4 wide (Arial Narrow Bold) and
centred on the box centre (12,12) by its ink box, so the letters sit in the middle on every side."""
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen

font = TTFont("/System/Library/Fonts/Supplemental/Arial Narrow Bold.ttf")
gs = font.getGlyphSet(); cmap = font.getBestCmap()
TEXT = "AUTO"; TRACK = 40  # font units between letters
# lay out in font units
x = 0; placed = []
for ch in TEXT:
    g = gs[cmap[ord(ch)]]
    bp = BoundsPen(gs); g.draw(bp)
    placed.append((g, x))
    x += g.width + TRACK
rec = RecordingPen()
for g, ox in placed:
    g.draw(TransformPen(rec, (1, 0, 0, 1, ox, 0)))
bp = BoundsPen(gs); rec.replay(bp)
x0, y0, x1, y1 = bp.bounds
W = 16.4
s = W / (x1 - x0)
cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
# font y is up; image y is down; centre on (12,12)
pen = SVGPathPen(gs, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
rec.replay(TransformPen(pen, (s, 0, 0, -s, 12 - cx * s, 12 + cy * s)))
letters = pen.getCommands()
box = "M4,2H20A2,2 0 0 1 22,4V20A2,2 0 0 1 20,22H4A2,2 0 0 1 2,20V4A2,2 0 0 1 4,2Z"
